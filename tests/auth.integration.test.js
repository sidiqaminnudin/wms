import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import http from 'node:http';
import { chromium } from '@playwright/test';
import argon2 from 'argon2';
import { createApp } from '../src/app.js';
import { getConfig } from '../src/config.js';
import { migrate } from '../src/migrate.js';

const url = process.env.TEST_DATABASE_URL;
test('PostgreSQL auth, rotation, company/warehouse isolation, revocation and logout', { skip: !url }, async () => {
  const schema = `auth_test_${randomUUID().replaceAll('-', '')}`;
  const admin = new pg.Pool({ connectionString: url });
  await admin.query(`CREATE SCHEMA ${schema}`);
  const pool = new pg.Pool({ connectionString: url, options: `-c search_path=${schema},public` });
  let app;
  let server;
  try {
    await migrate({ pool });
    await migrate({ pool });
    const companies = (await pool.query('SELECT id FROM companies ORDER BY code')).rows;
    const [a, b] = companies.map(row => row.id);
    const hash = await argon2.hash(randomUUID(), { type: argon2.argon2id });
    const password = randomUUID();
    const user = (await pool.query('INSERT INTO users(username,name,password_hash) VALUES ($1,$2,$3) RETURNING id', ['integration', 'Integration User', await argon2.hash(password)])).rows[0].id;
    const role = (await pool.query("SELECT id FROM roles WHERE code='VIEWER'")).rows[0].id;
    await pool.query('INSERT INTO user_company_roles VALUES ($1,$2,$3)', [user, a, role]);
    const wa = (await pool.query("INSERT INTO warehouses(operator_company_id,code,name) VALUES ($1,'TEST-A','Test A') RETURNING id", [a])).rows[0].id;
    const wb = (await pool.query("INSERT INTO warehouses(operator_company_id,code,name) VALUES ($1,'TEST-B','Test B') RETURNING id", [b])).rows[0].id;
    await pool.query('INSERT INTO user_warehouse_access VALUES ($1,$2),($1,$3)', [user, wa, wb]);
    server = http.createServer();
    server.listen(0, '127.0.0.1');
    await new Promise(resolve => server.once('listening', resolve));
    const origin = `http://127.0.0.1:${server.address().port}`;
    app = createApp({ preview: false, pool, config: getConfig({ SESSION_SECRET: randomUUID(), APP_ORIGIN: origin }) });
    server.on('request', app);
    const base = `${origin}/api/v1/auth`;
    let cookie = '';
    let token;
    const call = async (path, body, extra = {}) => {
      const response = await fetch(base + path, { method: body === undefined ? 'GET' : 'POST', headers: { Cookie: cookie, Origin: origin, 'Content-Type': 'application/json', 'X-CSRF-Token': token || '', ...extra }, body: body === undefined ? undefined : JSON.stringify(body) });
      if (response.headers.get('set-cookie')) cookie = response.headers.get('set-cookie').split(';')[0];
      const data = response.status === 204 ? null : await response.json();
      return { status: response.status, data };
    };
    assert.equal((await call('/me')).status, 401);
    const browser = await chromium.launch({ headless: true });
    try {
      const page = await browser.newPage();
      await page.goto(`http://127.0.0.1:${server.address().port}/login`);
      await page.getByLabel('Username').fill('integration');
      await page.getByLabel('Password').fill(password);
      await page.getByRole('button', { name: 'Masuk' }).click();
      await page.waitForURL('**/account');
      await page.locator('#userName').filter({ hasText: 'Integration User' }).waitFor();
      await pool.query('INSERT INTO user_company_roles VALUES ($1,$2,$3)', [user, b, role]);
      await page.reload();
      await page.locator('#companySelect option').nth(1).waitFor({ state: 'attached' });
      await page.locator('#companySelect').selectOption(b);
      await Promise.all([page.waitForResponse(response => response.url().endsWith('/active-company') && response.status() === 200), page.getByRole('button', { name: 'Ganti perusahaan' }).click()]);
      await page.getByText('TEST-B — Test B', { exact: true }).waitFor();
      await page.reload();
      await page.getByText('TEST-B — Test B', { exact: true }).waitFor();
      assert.equal(await page.locator('#companySelect').inputValue(), b);
      await pool.query('DELETE FROM user_company_roles WHERE user_id=$1 AND company_id=$2', [user, b]);
      await page.getByRole('button', { name: 'Keluar' }).click();
      await page.waitForURL('**/login');
    } finally { await browser.close(); }
    token = (await call('/csrf')).data.data.csrf_token;
    const anonymous = cookie;
    assert.equal((await call('/login', { username: 'integration', password }, { Origin: 'https://evil.example' })).status, 403);
    assert.equal((await call('/login', { username: 'integration', password: 'wrong' })).status, 401);
    const login = await call('/login', { username: 'integration', password });
    assert.equal(login.status, 200);
    assert.notEqual(cookie, anonymous);
    const staleToken = token;
    token = login.data.data.csrf_token;
    assert.notEqual(token, staleToken);
    assert.equal((await call('/me', undefined, { Cookie: anonymous })).status, 401);
    assert.deepEqual((await call('/warehouses')).data.data.map(w => w.id), [wa]);
    assert.equal((await call(`/warehouses/${wb}`)).status, 403);
    assert.equal((await call('/active-company', { company_id: b })).status, 403);
    assert.equal((await call('/active-company', { company_id: '------------------------------------' })).status, 400);
    await pool.query('INSERT INTO user_company_roles VALUES ($1,$2,$3)', [user, b, role]);
    const oldCookie = cookie;
    const switched = await call('/active-company', { company_id: b });
    assert.equal(switched.status, 200);
    token = switched.data.data.csrf_token;
    assert.notEqual(cookie, oldCookie);
    assert.equal((await call(`/warehouses/${wa}`)).status, 403);
    assert.deepEqual((await call('/warehouses')).data.data.map(w => w.id), [wb]);
    assert.equal((await call('/logout', {}, { 'X-CSRF-Token': staleToken })).status, 403);
    await pool.query('DELETE FROM role_permissions WHERE role_id=$1', [role]);
    assert.equal((await call('/warehouses')).status, 403);
    assert.equal((await call('/logout', {})).status, 204);
    assert.equal((await call('/me')).status, 401);
    assert.ok(hash.startsWith('$argon2id$'));
  } finally {
    if (server) await new Promise(resolve => server.close(resolve));
    if (app) await app.locals.close(); else await pool.end();
    await admin.query(`DROP SCHEMA ${schema} CASCADE`);
    await admin.end();
  }
});
